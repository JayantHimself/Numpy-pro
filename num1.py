import numpy as np

# Create an array
numbers = np.array([10, 20, 30, 40, 50])

print("Array:", numbers)

# Basic calculations
print("Sum:", np.sum(numbers))
print("Average:", np.mean(numbers))
print("Maximum:", np.max(numbers))
print("Minimum:", np.min(numbers))

# Multiply every element by 2
print("Array × 2:", numbers * 2)